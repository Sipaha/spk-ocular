#!/usr/bin/env python3
"""Generate tiny freestanding Linux rename helpers; build needs clang, not libc."""
import base64
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile
import os

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "internal/api/renamehelper"
SCRATCH = ROOT.parent / ".tmp"
SCRATCH.mkdir(exist_ok=True)


def text_section(obj, machine):
    data = obj.read_bytes()
    header = struct.unpack_from("<16sHHIQQQIHHHHHH", data)
    assert header[0][:6] == b"\x7fELF\x02\x01"
    assert header[1] == 1 and header[2] == machine
    offset, size, count, strings = header[6], header[11], header[12], header[13]
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, offset + i * size) for i in range(count)]
    names = data[sections[strings][4]:sections[strings][4] + sections[strings][5]]
    code = None
    for section in sections:
        name = names[section[0]:].split(b"\0", 1)[0]
        if section[1] in (4, 9) and section[5]:
            raise ValueError("rename helper must not contain unresolved relocations")
        if name == b".text":
            code = data[section[4]:section[4] + section[5]]
    assert code
    return code


def executable(code, machine):
    base, entry = 0x400000, 176
    ident = b"\x7fELF\x02\x01\x01" + bytes(9)
    header = struct.pack("<16sHHIQQQIHHHHHH", ident, 2, machine, 1, base + entry, 64, 0, 0, 64, 56, 2, 0, 0, 0)
    program = struct.pack("<IIQQQQQQ", 1, 5, 0, base, base, entry + len(code), entry + len(code), 4096)
    stack = struct.pack("<IIQQQQQQ", 0x6474E551, 6, 0, 0, 0, 0, 0, 16)
    return header + program + stack + code


parts = ["// Code generated by scripts/gen-rename-helper.py; DO NOT EDIT.\npackage api\n"]
with tempfile.TemporaryDirectory(prefix="rename-helper-", dir=SCRATCH) as tmp:
    for arch, target, machine in [("amd64", "x86_64-linux-gnu", 62), ("arm64", "aarch64-linux-gnu", 183)]:
        source = SOURCES / f"{arch}.S"
        obj = Path(tmp) / f"{arch}.o"
        subprocess.run(["clang", "--target=" + target, "-c", str(source), "-o", str(obj)], cwd=ROOT,
                       env={**os.environ, "TMPDIR": tmp}, check=True)
        blob = executable(text_section(obj, machine), machine)
        parts.append(f'const renameHelper{arch.upper()} = "{base64.b64encode(blob).decode()}"\n')
        parts.append(f'const renameHelper{arch.upper()}SourceSHA256 = "{hashlib.sha256(source.read_bytes()).hexdigest()}"\n')
output = ROOT / "internal/api/rename_helper_programs.go"
output.write_text("\n".join(parts))
subprocess.run(["gofmt", "-w", str(output)], cwd=ROOT, check=True)
