test('Helm release details, history, review and deletion use the embedded SDK', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('option', { name: /^demo\b/ }).click()
  await connectSelected(page)
  const nav = page.getByRole('navigation', { name: 'resources' })
  await nav.getByRole('button', { name: /^Helm \(2\)$/ }).click()
  await nav.getByRole('button', { name: 'Releases', exact: true }).click()
  const workspace = page.locator('.helm-workspace')
  await workspace.getByRole('gridcell', { name: 'demo-web', exact: true }).click()
  await expect(workspace.getByText('replicas: 2', { exact: true })).toBeVisible()
  const detailsPanel = workspace.locator('[data-area="details"]')
  const separator = detailsPanel.getByRole('separator', { name: 'Resize details panel', exact: true })
  const width = (await detailsPanel.boundingBox())!.width
  const box = (await separator.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x - 80, box.y + box.height / 2, { steps: 8 })
  await page.mouse.up()
  expect((await detailsPanel.boundingBox())!.width).toBeCloseTo(width + 82, 0)
  await separator.press('ArrowRight')
  const resized = (await detailsPanel.boundingBox())!.width
  expect(resized).toBeCloseTo(width + 62, 0)
  const resizedBox = (await separator.boundingBox())!
  await page.mouse.move(resizedBox.x + 2, resizedBox.y + 100)
  await page.mouse.down()
  await page.mouse.move(resizedBox.x - 40, resizedBox.y + 100, { steps: 5 })
  await page.keyboard.press('Escape')
  await page.mouse.up()
  expect((await detailsPanel.boundingBox())!.width).toBeCloseTo(resized, 0)
  const nameColumn = workspace.getByRole('separator', { name: 'Resize column Name', exact: true })
  await nameColumn.press('ArrowRight')

  await workspace.getByRole('tab', { name: 'Computed values', exact: true }).click()
  await expect(workspace.getByText('replicas: 2', { exact: true })).toBeVisible()
  await workspace.getByRole('tab', { name: 'History', exact: true }).click()
  await expect(workspace.getByRole('button', { name: '#1 · 1.2.0 · deployed' })).toBeVisible()
  await expect(workspace.getByRole('tab', { name: 'History', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(workspace.getByRole('tab', { name: 'Values', exact: true })).toHaveAttribute('aria-selected', 'false')
  await page.screenshot({ path: join(scratchRoot, 'helm-releases.png') })
  await workspace.getByRole('button', { name: 'Uninstall', exact: true }).click()
  await expect(workspace.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('demo-web')
  await workspace.getByRole('button', { name: 'Review operation' }).click()
  await expect(workspace.getByText('Hooks may run workloads', { exact: false })).toBeVisible()
  const auth = { Authorization: `Bearer ${await token(page)}`, Origin: new URL(page.url()).origin }
  const read = () => page.request.post('/api/Helm', { headers: auth, data: { command: 'list', provider: 'synthetic', target: 'demo', scope: { mode: 'all' } } })
  expect((await (await read()).json()).releases).toHaveLength(1)
  await page.screenshot({ path: join(scratchRoot, 'helm-review.png') })
  await workspace.getByRole('button', { name: 'Execute reviewed operation' }).click()
  await expect(workspace.getByText('Helm operation completed.', { exact: true })).toBeVisible()
  expect((await (await read()).json()).releases ?? []).toHaveLength(0)
})

