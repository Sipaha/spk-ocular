func TestRenameAndRemoveConfigurationsPreserveIdentityAndOriginalFiles(t *testing.T) {
	home, dir := t.TempDir(), t.TempDir()
	original := kubeconfig("", "one")
	path := write(t, filepath.Join(home, ".kube", "config"), original)
	p := managed(t, home, dir)
	st, err := p.Configurations(ConfigRequest{Command: "import", Paths: []string{path}})
	require.NoError(t, err)
	entry := st.Entries[0]
	before := p.loadConfigured().Contexts[0]
	st, err = p.Configurations(ConfigRequest{Command: "rename", ID: entry.ID, Expect: entry.Revision, Name: "Production"})
	require.NoError(t, err)
	after := p.loadConfigured().Contexts[0]
	require.Equal(t, before.ID, after.ID)
	require.Equal(t, before.Hash, after.Hash)
	require.Equal(t, before.Identity, after.Identity)
	require.Equal(t, "Production / one", target(after).Title)
	_, err = p.Configurations(ConfigRequest{Command: "remove", ID: entry.ID, Expect: entry.Revision})
	require.ErrorContains(t, err, "changed")
	p = managed(t, home, dir)
	st, err = p.Configurations(ConfigRequest{Command: "status"})
	require.NoError(t, err)
	require.Equal(t, "Production", st.Entries[0].Name)
	st, err = p.Configurations(ConfigRequest{Command: "remove", ID: entry.ID, Expect: st.Entries[0].Revision})
	require.NoError(t, err)
	require.Empty(t, st.Entries)
	require.Empty(t, p.loadConfigured().Contexts)
	b, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Equal(t, original, string(b))
	p = managed(t, home, dir)
	require.Empty(t, p.loadConfigured().Contexts)
}
