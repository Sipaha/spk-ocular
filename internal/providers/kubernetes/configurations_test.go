func TestExplicitConfigurationsImportAndRestart(t *testing.T) {
	home, dir := t.TempDir(), t.TempDir()
	main := write(t, filepath.Join(home, ".kube", "config"), kubeconfig("", "one"))
	extra := write(t, filepath.Join(home, ".kube", "other"), kubeconfig("", "two"))
	p := managed(t, home, dir)
	d, err := p.Discover(context.Background())
	require.NoError(t, err)
	require.Empty(t, d.Targets)
	s, err := p.Configurations(ConfigRequest{Command: "status"})
	require.NoError(t, err)
	require.False(t, s.Initialized)
	require.Len(t, s.Candidates, 2)
	_, err = p.Configurations(ConfigRequest{Command: "import", Paths: []string{main}})
	require.NoError(t, err)
	p = managed(t, home, dir)
	d, err = p.Discover(context.Background())
	require.NoError(t, err)
	require.Len(t, d.Targets, 1)
	require.Equal(t, "kubeconfig:one", d.Targets[0].ID)
	write(t, extra, kubeconfig("", "two", "three"))
	d, err = p.Discover(context.Background())
	require.NoError(t, err)
	require.Len(t, d.Targets, 1)
	write(t, main, kubeconfig("", "one", "new"))
	d, err = p.Discover(context.Background())
	require.NoError(t, err)
	require.Len(t, d.Targets, 2)
	_, err = p.Configurations(ConfigRequest{Command: "import", Paths: []string{filepath.Join(home, "unlisted")}})
	require.Error(t, err)
}
func TestEncryptedConfigurationsNeverPersistPlaintext(t *testing.T) {
	home, dir := t.TempDir(), t.TempDir()
	p := managed(t, home, dir)
	password := "tiny42"
	_, err := p.Configurations(ConfigRequest{Command: "create", Name: "private", YAML: kubeconfig("", "private")})
	require.Error(t, err)
	_, err = p.Configurations(ConfigRequest{Command: "setup", Password: password})
	require.NoError(t, err)
	yaml := strings.ReplaceAll(kubeconfig("", "private"), "SECRET-private", "VERY-SECRET-CONFIG-TOKEN")
	state, err := p.Configurations(ConfigRequest{Command: "create", Name: "my cluster", YAML: yaml})
	require.NoError(t, err)
	require.Len(t, state.Entries, 1)
	b, err := os.ReadFile(filepath.Join(dir, "kubeconfigs.json"))
	require.NoError(t, err)
	require.NotContains(t, string(b), "VERY-SECRET-CONFIG-TOKEN")
	require.NotContains(t, string(b), password)
	require.NotContains(t, string(b), "https://private")
	loaded := p.loadConfigured()
	require.Len(t, loaded.Contexts, 1)
	cfg, err := restConfig(loaded.Contexts[0])
	require.NoError(t, err)
	require.Equal(t, "VERY-SECRET-CONFIG-TOKEN", cfg.BearerToken)
	p = managed(t, home, dir)
	state, err = p.Configurations(ConfigRequest{Command: "status"})
	require.NoError(t, err)
	require.True(t, state.Locked)
	require.Len(t, p.loadConfigured().Contexts, 1)
	require.True(t, p.loadConfigured().Contexts[0].Locked)
	require.Nil(t, p.loadConfigured().Contexts[0].Config)
	_, err = p.Configurations(ConfigRequest{Command: "unlock", Password: "wrong"})
	require.Error(t, err)
	require.Len(t, p.loadConfigured().Contexts, 1)
	require.True(t, p.loadConfigured().Contexts[0].Locked)
	require.Nil(t, p.loadConfigured().Contexts[0].Config)
	_, err = p.Configurations(ConfigRequest{Command: "unlock", Password: password})
	require.NoError(t, err)
	require.Len(t, p.loadConfigured().Contexts, 1)
	_, err = p.Configurations(ConfigRequest{Command: "setup", Password: password})
	require.Error(t, err)
}
func TestConfigurationCipherBindsRecordAndDetectsTampering(t *testing.T) {
	key := make([]byte, 32)
	a, err := sealConfig(key, []byte("secret"), "a")
	require.NoError(t, err)
	b, err := sealConfig(key, []byte("secret"), "a")
	require.NoError(t, err)
	require.NotEqual(t, a, b)
	_, err = openConfig(key, a, "b")
	require.Error(t, err)
	a[len(a)-1] ^= 1
	_, err = openConfig(key, a, "a")
	require.Error(t, err)
}
